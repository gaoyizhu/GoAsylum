// 格式化翻译文本（支持占位符）
export function formatTranslation(text: string, ...args: (string | number)[]): string {
  return text.replace(/{(\d+)}/g, (match, index) => {
    const argIndex = parseInt(index, 10);
    return args[argIndex] !== undefined ? String(args[argIndex]) : match;
  });
}
